#!/usr/bin/env python3
"""Generate the per-feature diagram-studio/1 JSON files for privilege-map-LAB.

Each diagram is one per feature card in src/data/features.json ("diagram" field).
Layout convention: columns at x in {0, 320, 640, 960}, rows at y in steps of 130,
node boxes are 210x100 (test requires >=210 dx or >=110 dy between any pair).
Every edge is labelled; steps cover every edge.
"""
import json, os, sys

OUT = os.path.join(os.path.dirname(__file__), "..", "diagrams")

def D(id_, title, lede, groups, nodes, edges, steps):
    return {"schema": "diagram-studio/1", "id": id_, "title": title, "lede": lede,
            "groups": groups, "nodes": nodes, "edges": edges, "steps": steps}

def N(id_, group, label, sub, x, y):
    return {"id": id_, "group": group, "label": label, "sub": sub, "x": x, "y": y}

def E(s, t, label, dashed=False):
    e = {"source": s, "target": t, "label": label}
    if dashed: e["dashed"] = True
    return e

def S(title, what, why, edges):
    return {"title": title, "what": what, "why": why, "edges": edges}

def stepcover(diagram):
    """Assign steps greedily: each step already carries explicit edge indexes."""
    covered = sorted(set(i for s in diagram["steps"] for i in s["edges"]))
    assert covered == list(range(len(diagram["edges"]))), f'{diagram["id"]}: edges not covered {covered}'
    return diagram

def write(diagram):
    stepcover(diagram)
    with open(os.path.join(OUT, diagram["id"] + ".json"), "w") as f:
        json.dump(diagram, f, indent=2)
        f.write("\n")

